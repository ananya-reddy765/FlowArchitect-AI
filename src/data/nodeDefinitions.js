// Sidebar group order (matches the spec's Node Library categories).
export const nodeGroups = [
  "Triggers",
  "Communication",
  "Data",
  "Storage",
  "Web",
  "Logic",
  "Data Transformation",
  "AI",
  "Utility",
  "Output",
  "Files",
  "Productivity",
  "Other n8n Nodes",
];

export function nodesByGroup() {
  const grouped = {};
  nodeGroups.forEach((group) => (grouped[group] = []));

  Object.entries(nodeDefinitions).forEach(([key, def]) => {
    grouped[def.group].push({ key, ...def });
  });

  return grouped;
}
